import fs from 'node:fs'
import assert from 'node:assert/strict'
const read = path => fs.readFileSync(path, 'utf8')
const layout = read('src/app/(app)/layout.tsx')
const more = read('src/app/(app)/more/page.tsx')
const policy = read('src/lib/mobileUpdatePolicy.ts')
const service = read('src/lib/mobileUpdateService.ts')
const hook = read('src/hooks/useApkUpdate.ts')
const banner = read('src/components/AppUpdateBanner.tsx')
const page = read('src/app/(app)/updates/page.tsx')
const workflow = read('.github/workflows/android-build.yml')
const serverUrl = read('src/lib/runtime/apiUrl.ts')
assert(layout.includes('<AppUpdateBanner />'), 'Aviso global não montado')
assert(more.includes('href="/updates"'), 'Central de Atualizações não navegável')
assert(policy.includes("APK_ARTIFACT_NAME = 'DFL-Finance-App'"))
assert(policy.includes("run.conclusion !== 'success'"), 'Sem verificação de sucesso')
assert(policy.includes('artifact.expires_at'), 'Sem vencimento real')
assert(policy.includes('release.build > installedBuild'), 'Sem comparar com APK instalado')
assert(service.includes('api.github.com/repos/'), 'Consulta não é pública')
assert(!/Authorization|Bearer|GITHUB_TOKEN|PRIVATE_TOKEN|service_role/.test(service), 'Proibido token no APK')
assert(hook.includes('App.getInfo()'), 'Versão do Android não consultada')
assert(hook.includes('Capacitor.isNativePlatform()'), 'PWA confundido com APK')
assert(banner.includes('formatApkExpiry'), 'Prazo não aparece no banner')
assert(banner.includes('SNOOZE_HOURS'), 'Lembrar depois ausente')
assert(page.includes('Verificar') && page.includes('Abrir GitHub Actions'), 'Central sem consulta ou acesso')
assert(workflow.includes('retention-days: 14'), 'Contrato de retenção alterado')
assert(workflow.includes('GITHUB_RUN_NUMBER'), 'versionCode deixou de seguir a Action')
assert(workflow.includes('DFL-Finance-App'), 'Artefato nativo divergiu')
assert(workflow.includes('R456 APK updates certification'), 'Action sem gate R456')
assert(serverUrl.includes('NEXT_PUBLIC_DFL_SERVER_ORIGIN'), 'Fronteira mobile alterada')
assert(!/installPackage|REQUEST_INSTALL_PACKAGES|PackageInstaller|silent.?install/i.test([banner, service, hook, page].join('\n')), 'Instalação silenciosa proibida')
console.log('R456: 19 contratos de GitHub, APK, PWA, expiração, UX e segurança aprovados')
