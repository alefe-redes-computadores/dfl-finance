import fs from 'node:fs'
const read=(f)=>fs.readFileSync(f,'utf8'); const ok=(v,m)=>{if(!v) throw new Error(m)}
const settings=read('src/lib/userSettings.ts'); const more=read('src/app/(app)/more/page.tsx'); const native=read('src/lib/nativeNotifications.ts'); const runtime=read('src/components/CapacitorStatusBar.tsx'); const patch=read('scripts/patch-android-system-bars-v15.mjs'); const icon=read('assets/android/ic_stat_dfl_finance.xml')
ok(settings.includes('push_notifications: false,'),'Notificações não começam OFF')
ok(more.includes('push_notifications ?? false'),'UI sem fallback OFF')
ok(native.includes('async function hasNotificationPermission()'),'Scheduler sem check-only')
ok(native.includes('LocalNotifications.checkPermissions()'),'checkPermissions ausente')
ok(native.includes('LocalNotifications.requestPermissions()'),'request explícito ausente')
ok(!native.includes('const permitted = await ensurePermission()'),'Scheduler ainda chama ensurePermission')
ok(runtime.includes("registerPlugin<SystemBarsPlugin>('SystemBars')"),'Bridge SystemBars ausente')
ok(runtime.includes("SystemBars.setTheme({ dark: theme === 'dark' })"),'Tema não chega à ponte')
const g=runtime.indexOf("if (platform === 'android')"), r=runtime.indexOf('return',g)
ok(g>=0&&r>g,'Guarda Android inválida')
ok(runtime.indexOf('StatusBar.setStyle',g)>r,'React ainda controla setStyle Android')
ok(runtime.indexOf('StatusBar.setOverlaysWebView',g)>r,'React ainda controla overlay Android')
ok(patch.includes('SystemBarsPlugin'),'Patch não gera SystemBarsPlugin')
ok(patch.includes('setAppearanceLightStatusBars(!dark)'),'Contraste dinâmico nativo ausente')
ok(icon.includes('#FFFFFFFF')&&icon.includes('android:pathData='),'Ícone monocromático inválido')
console.log('DFL FINANCE V32 NATIVE FREEZE: OK')
