function compile(fnName,extra=''){
 const key=`function ${fnName}(`;
 const p=txt.indexOf(key);assert.ok(p>=0,'Sem funcao '+fnName);
 const next=txt.indexOf('\n}\n',p);assert.ok(next>p,'Funcao sem fechamento: '+fnName);
 const raw=txt.slice(p,next+3)+`\nexports.target=${fnName};`+extra;
 const code=ts.transpileModule(raw,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
 const ctx={exports:{},Date,String,Number};vm.runInNewContext(code,ctx,{timeout:1000});return ctx.exports.target;
}
