import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import ts from 'typescript';
import {execFileSync} from 'node:child_process';
const current='supabase/functions/whatsapp-webhook/index.ts';
const candidate='supabase/functions/whatsapp-webhook/index.r357-canary.ts';
const original=execFileSync('git',['show','d61605df99700571d94733a6983855e4a33f2f82:'+current],{encoding:'utf8'});
const live=fs.readFileSync(current,'utf8');
assert.equal(live,original,'Arquivo ativo do webhook alterado, BLOQUEADO');
const data=fs.readFileSync(candidate,'utf8');
const syntax=ts.createSourceFile(candidate,data,ts.ScriptTarget.ES2022,true,ts.ScriptKind.TS);
assert.equal(syntax.parseDiagnostics.length,0,'ERRO SINTATICO NO CANDIDATO TS: '+syntax.parseDiagnostics.map(x=>x.messageText).join('; '));
assert.equal((data.match(/function r357CanaryDecision\(/g)||[]).length,1);
assert.equal((data.match(/DFL_V2_FROZEN_LEGACY_FALLBACK_DENIED/g)||[]).length,1);
assert.equal((data.match(/const v2Requested=r357Decision==='canary'/g)||[]).length,1);
assert.match(data,/const atomicMode=false;/);
assert.match(data,/if\(r357Decision==='blocked'\)throw/);
assert.match(data,/previousV2\.data\?\.temp_data\?\.atomic_snapshot/);
assert.match(data,/recoverAtomicV2Handoff\(input\)/);
assert.match(data,/DFL_ATOMIC_POSTCOMMIT_LEDGER_NOT_VERIFIED/);
assert.match(data,/const r=atomicMode[\s\S]*?\? await atomicBotSingle[\s\S]*?: v2Mode[\s\S]*?: await db\.rpc\(rpc,params\);/);
// Extrai a funcao real do candidato e executa 12 cenarios sem chamadas remotas.
const match=data.match(/function r357CanaryDecision\([\s\S]*?\n}\n/);
assert.ok(match,'GATE NAO ENCONTRADO');
const js=ts.transpileModule(match[0]+ '\nexports.check=r357CanaryDecision;',
 {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const ctx={exports:{},Date,Number,String};
vm.runInNewContext(js,ctx,{timeout:1000});
const check=ctx.exports.check;
assert.equal(typeof check,'function');
const user='12345678-1234-4234-8234-123456789abc';
const phone='5534999999999';
const now=Date.parse('2026-10-27T20:00:00Z');
const base={enabled:'true',gate:'r330-db-approved',canaryPhone:phone,canaryUser:user,until:'2026-10-27T20:07:00Z'};
const call=(overrides={},ph=phone,id=user,t=now)=>check(ph,id,{...base,...overrides},t);
assert.equal(call(),'canary','permitir canario valido');
assert.equal(call({},'+55 (34) 99999-9999'),'canary','normalizacao telefone');
assert.equal(call({enabled:'false'}),'legacy','flag OFF');
assert.equal(call({enabled:undefined}),'legacy','flag ausente');
assert.equal(call({canaryPhone:''}),'legacy','telefone ausente');
assert.equal(call({canaryPhone:'123'}),'legacy','telefone curto');
assert.equal(call({},'5534999999998'),'legacy','numero diferente');
assert.equal(call({},phone,'22345678-1234-4234-8234-123456789abc'),'legacy','usuario diferente');
assert.equal(call({gate:'errado'}),'blocked','gate divergente deve falhar fechado');
assert.equal(call({until:'not-date'}),'blocked','data invalida bloqueia');
assert.equal(call({until:'2026-10-27T19:59:00Z'}),'blocked','janela expirada');
assert.equal(call({until:'2026-10-27T20:11:00Z'}),'blocked','janela muito longa');
assert.equal(call({},phone,user,now+7*60*1000),'blocked','expiracao exata');
assert.equal(call({canaryUser:'invalid'}),'legacy','UUID invalido');
// O candidato deve conter a fonte original, sem mexer nas outras rotas.
assert.equal((data.match(/serve\(async req=>/g)||[]).length,1,'entrada do webhook preservada');
assert.equal((data.match(/DFL_BOT_ATOMIC_SINGLE_V1/g)||[]).length,1,'trava V1 preservada');
console.log('=== R357 APROVADA: 14 cenarios de alvo, TTL, gates e fallback; codigo de producao intacto ===');
