import assert from 'node:assert/strict'
import fs from 'node:fs'
let checks=0
const read=p=>fs.readFileSync(p,'utf8')
const ok=(name,condition)=>{assert.ok(condition,name);checks++;console.log('OK:',name)}
const proposal=read('docs/sql-candidates/gate-f-f1-debt-payment-proposal.sql')
const bot=read('supabase/functions/whatsapp-webhook/index.ts')
const ledger=read('src/lib/debtOperations.ts')
const credits=read('src/lib/debtCreditOperations.ts')
const a=read('src/lib/atomicFinancialSync.ts')
const saleTest=read('scripts/check-gatef-f1-sale-identity.mjs')
ok('Proposta SQL somente docs/sql-candidates',fs.existsSync('docs/sql-candidates/gate-f-f1-debt-payment-proposal.sql'))
ok('Proposta explicita que nao eh migracao',proposal.includes('NAO EXECUTAR EM PRODUCAO'))
ok('Preserva assinatura do RPC sem vazar status novo',proposal.includes('CREATE OR REPLACE FUNCTION public.bot_record_debt_payment(') && /RETURNS jsonb/.test(proposal))
ok('Exige identidade confirmada',proposal.includes('DFL_PAYMENT_IDENTITY_REQUIRED'))
ok('Exige chave de idempotencia e recusa reuse divergente',proposal.includes('DFL_PAYMENT_IDEMPOTENCY_REQUIRED')&&proposal.includes('DFL_PAYMENT_IDEMPOTENCY_CONFLICT'))
ok('Advisory lock alinhado por usuario',proposal.includes("hashtextextended(p_user_id::text,0)")&&a.includes('dfl_commit_financial_batch'))
ok('Replay compara chave, titular, conta, divida e valor', ['v_tx.user_id','v_tx.account_id','v_tx.debt_id','v_tx.amount'].every(t=>proposal.includes(t)))
ok('Replay nao altera saldos antes da verificacao', proposal.indexOf('IF FOUND THEN') < proposal.indexOf('UPDATE public.accounts'))
ok('Pagamento parcial e quitacao somente status permitidos',proposal.includes("WHEN v_paid>0 THEN 'partial' ELSE 'pending'")&&proposal.includes("THEN 'paid'"))
ok('Proibido criar status cancelled/disputed na coluna de divida',!/(?:SET|VALUES|THEN)\s+['"](?:cancelled|disputed|frozen)['"]/i.test(proposal))
ok('Origem permitida preservada',proposal.includes("'whatsapp',p_idempotency_key")&&!/['"](?:site|entregas|finance_whatsapp)['"]/.test(proposal))
ok('Proposta nao contem chamada rede ou env secreto',!/(https?:\/\/|supabase\.co|fetch\(|Deno\.env|process\.env)/i.test(proposal))
ok('RPC continua security invoker e grants restritos',proposal.includes('SECURITY INVOKER')&&proposal.includes('FROM PUBLIC, anon, authenticated'))
ok('Saldo so com transacao marcada done',proposal.includes("v_date,'done',TRUE,v_debt.context"))
ok('Data civil Sao Paulo explicitamente controlada',proposal.includes("'America/Sao_Paulo'"))
ok('Webhook privado original chama RPC com chave',bot.includes('bot_record_debt_payment')&&bot.includes('p_idempotency_key:key'))
ok('Bot consulta user_phones como barreira',bot.includes('user_phones'))
ok('Ledger financeiro preservado',ledger.includes('getDebtStatusFromAmounts')&&ledger.includes('getDebtLedgerState'))
ok('Aplicacao credito existente usa transacao Dexie',credits.includes("db.transaction('rw'"))
ok('Contrato futuro recusa identidade so por telefone',saleTest.includes('CONFIRMED_CONTACT_ID_REQUIRED'))
ok('Contrato futuro preserva site:ID no espelhamento',saleTest.includes('entregas_site_mirror'))
ok('Contrato futuro nao ativa bridge nem mensageria',!/(\bfetch\(|supabase\.rpc|\.send\()/.test(saleTest))
console.log(`GATE F F1: ${checks} contratos estaticos aprovados; sem alteracoes externas.`)
