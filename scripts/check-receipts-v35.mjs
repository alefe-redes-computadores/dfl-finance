import fs from 'node:fs'
const read = (f) => fs.readFileSync(f, 'utf8')
const ok = (v, m) => { if (!v) throw new Error(`V35: ${m}`) }
const page = read('src/app/(app)/receipts/page.tsx')
const more = read('src/app/(app)/more/page.tsx')
const exportService = read('src/lib/services/exportService.ts')
const pkg = JSON.parse(read('package.json'))
ok(more.includes('Central de Comprovantes') && more.includes('href="/receipts"'), 'atalho da central ausente')
ok(page.includes('groupedReceipts'), 'agrupamento mensal ausente')
ok(page.includes('display_name'), 'nome de apresentação ausente')
ok(page.includes('account_name') && page.includes('bank_name'), 'contexto bancário ausente')
ok(page.includes('Abrir lançamento'), 'deep-link para lançamento ausente')
ok(page.includes("import('@capacitor/browser')"), 'abertura nativa de comprovante ausente')
ok(page.includes('Buscar loja, banco, valor, data...'), 'busca inteligente ausente')
ok(page.includes('Arquivos anexados e arquivos avulsos'), 'suporte a avulsos removido')
ok(exportService.includes('URL.createObjectURL'), 'auditoria: export web mudou inesperadamente')
ok(Boolean(pkg.dependencies?.['@capacitor/browser']), '@capacitor/browser necessário para abertura nativa não instalado')
ok(!pkg.dependencies?.['@capacitor/filesystem'] && !pkg.dependencies?.['@capacitor/share'], 'V35 não deve introduzir plugins nativos e invalidar Native Freeze')
console.log('DFL FINANCE V35 CENTRAL DE COMPROVANTES: OK')
